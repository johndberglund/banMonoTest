// Geometric realization of a 2-isohedral tiling from its Delaney-Dress symbol, so that types
// whose two orbits are DIFFERENT shapes can be drawn. The rest of the engine is monohedral-only:
// tiler_core's develop() says as much in its own comment ("both orbits are this same m-gon") and
// solveTile solves for a single polygon.
//
// Method is Tegula's (Huson & Zeller, after Klaus Westphal) -- see
// references/TEGULA_ALGORITHM_NOTES.md for the extracted algorithm and provenance. Tegula is
// GPL-3; this is a re-implementation of the published method, not a copy of its code.
//
// STAGE 1 (this file, so far): parse the symbol and expose the chamber structure. The relaxation
// needs an incidence structure whose exact definition is still being confirmed against Tegula's
// data classes, so it is deliberately NOT guessed at here.
(function (root) {
  'use strict';

  // ---------------- Delaney-Dress symbol ----------------
  // Format:  <id.0:size:s0,s1,s2:m01,m12>
  // e.g.     <4.0:2:1 2,1 2,2:3 3,6>
  //          <1132.0:10:2 4 7 8 10,2 5 6 9 10,3 4 7 9 10:3 4,4 6>
  //
  // Flags are 1-based, `size` of them. Each si is an INVOLUTION written as the images of
  // 1,2,3,... in order, but abbreviated: the list only names each 2-cycle once as it is first
  // reached, so it is shorter than `size` whenever a flag is fixed or already paired. The robust
  // reading (and the one every Delaney-symbol parser uses) is: walk flags 1..size, and for each
  // flag not yet assigned, consume the next number from the list as its partner.
  //
  // m01 / m12 are per-ORBIT of <s0,s1> and <s1,s2> respectively, listed in order of first
  // occurrence. m01 gives the tile sizes, m12 the vertex degrees. m02 is always 2 for a tiling.
  function parseSymbol(sym) {
    const m = String(sym).trim().match(/^<\s*([^:]*):\s*([^:]*):\s*([^:]*):\s*([^>]*)>\s*$/);
    if (!m) throw new Error('unparseable Delaney symbol: ' + sym);
    const name = m[1].trim();
    const size = parseInt(m[2].trim().split(/\s+/)[0], 10);
    const invParts = m[3].split(',').map(s => s.trim());
    const mParts = m[4].split(',').map(s => s.trim());
    if (invParts.length !== 3) throw new Error('expected 3 involutions in ' + sym);
    const nums = s => (s.match(/-?\d+/g) || []).map(Number);

    // sigma[t][f] = image of flag f (1-based) under involution t
    const sigma = [];
    for (let t = 0; t < 3; t++) {
      const list = nums(invParts[t]);
      const s = new Array(size + 1).fill(0);
      let k = 0;
      for (let f = 1; f <= size; f++) {
        if (s[f]) continue;                       // already paired by an earlier flag
        if (k >= list.length) throw new Error(`involution ${t} ran out of entries in ${sym}`);
        const g = list[k++];
        if (g < 1 || g > size) throw new Error(`involution ${t} names flag ${g}, out of range, in ${sym}`);
        s[f] = g; s[g] = f;                       // fixed point when g === f
      }
      if (k !== list.length) throw new Error(`involution ${t} had ${list.length - k} unused entries in ${sym}`);
      sigma.push(s);
    }
    return { name, size, sigma, m01: nums(mParts[0]), m12: nums(mParts[1] === undefined ? '' : mParts[1]) };
  }

  // Orbits of the subgroup generated by involutions a and b, over flags 1..size.
  // Returns { orbitOf: Int32Array (flag -> orbit index), orbits: [[flags...]] } in order of
  // first occurrence, which is the order m01/m12 are listed in.
  function orbits2(D, a, b) {
    const orbitOf = new Int32Array(D.size + 1).fill(-1);
    const orbits = [];
    for (let f = 1; f <= D.size; f++) {
      if (orbitOf[f] >= 0) continue;
      const idx = orbits.length, members = [], stack = [f];
      orbitOf[f] = idx;
      while (stack.length) {
        const x = stack.pop(); members.push(x);
        for (const t of [a, b]) {
          const y = D.sigma[t][x];
          if (orbitOf[y] < 0) { orbitOf[y] = idx; stack.push(y); }
        }
      }
      members.sort((p, q) => p - q);
      orbits.push(members);
    }
    return { orbitOf, orbits };
  }

  // The three orbit families of a 2D Delaney symbol:
  //   tiles    = <s0,s1> orbits   (m01 = tile size)
  //   vertices = <s1,s2> orbits   (m12 = vertex degree)
  //   edges    = <s0,s2> orbits   (m02 = 2 always, for a tiling)
  function chambers(D) {
    const tiles = orbits2(D, 0, 1);
    const verts = orbits2(D, 1, 2);
    const edges = orbits2(D, 0, 2);
    return { tiles, verts, edges };
  }

  // The r-value of an <a,b> orbit: the number of times you must apply (sigma_a sigma_b) to return
  // to the start. Then m_ab = the symbol's declared value, and the branching number is m_ab / r.
  // A branching number > 1 is a rotation centre -- which is exactly what Tegula's relaxation
  // PINS (`if (d.getOrb(op).getI() > 1) continue;`), so it has to be computed correctly.
  function rValue(D, a, b, startFlag) {
    let f = startFlag, r = 0;
    do { f = D.sigma[b][D.sigma[a][f]]; r++; } while (f !== startFlag && r <= 2 * D.size);
    return r;
  }
  function branching(D, a, b, orbitList, declaredM) {
    return orbitList.map((members, i) => {
      const r = rValue(D, a, b, members[0]);
      const mv = declaredM[i];
      return { r, m: mv, v: mv === undefined ? undefined : mv / r };
    });
  }

  // ---------------- chamber incidence (Tegula's Node / Edge / Orbit) ----------------
  // Resolved from Glue.java (see TEGULA_ALGORITHM_NOTES.md). Tegula's three data classes are:
  //   Node  = a FLAG (chamber). Its single (x,y) is the chamber triangle's centroid.
  //   Orbit = a BARYCENTRIC POINT -- tile centre, edge midpoint or tiling vertex -- tagged `ty`.
  //   Edge  = a CHAMBER SIDE, shared by two flags.
  //
  // Type convention (John's, and the standard one): sigma_ty MOVES the type-ty corner and fixes
  // the other two. So the type-ty corner is the orbit of the COMPLEMENTARY pair:
  //   ty=0 -> <s1,s2> = tiling vertex     (moved by s0)
  //   ty=1 -> <s0,s2> = edge midpoint     (moved by s1)
  //   ty=2 -> <s0,s1> = tile centre       (moved by s2)
  // The chamber side of type ty lies OPPOSITE the type-ty corner, so its two endpoints are the
  // corners of the other two types -- which is exactly relax_edgs' two orbit coords.
  const PAIR = [[1, 2], [0, 2], [0, 1]];   // complement of each type

  function incidence(D) {
    const n = D.size;
    // one orbit family per type, in the type indexing above
    const fam = [orbits2(D, 1, 2), orbits2(D, 0, 2), orbits2(D, 0, 1)];
    const orbits = [], base = [];
    for (let ty = 0; ty < 3; ty++) {
      base[ty] = orbits.length;
      for (const members of fam[ty].orbits) orbits.push({ ty, members, ring: null });
    }
    const orbOf = (ty, f) => base[ty] + fam[ty].orbitOf[f];

    // Edges: the orbits of sigma_ty. A fixed point (sigma_ty(f) === f) gives a one-flag side.
    const edges = [], edgeIdx = [];
    for (let ty = 0; ty < 3; ty++) {
      edgeIdx[ty] = new Int32Array(n + 1).fill(-1);
      for (let f = 1; f <= n; f++) {
        if (edgeIdx[ty][f] >= 0) continue;
        const g = D.sigma[ty][f], e = edges.length;
        const [a, b] = PAIR[ty];
        edges.push({ ty, nodes: g === f ? [f] : [f, g], oc: [orbOf(a, f), orbOf(b, f)] });
        edgeIdx[ty][f] = e; edgeIdx[ty][g] = e;
      }
    }

    // Nodes: np/ep/op indexed by type, matching Node.java's np[3]/ep[3]/op[3].
    const nodes = [];
    for (let f = 1; f <= n; f++) {
      const np = [], ep = [], op = [];
      for (let ty = 0; ty < 3; ty++) {
        np.push(D.sigma[ty][f]); ep.push(edgeIdx[ty][f]); op.push(orbOf(ty, f));
      }
      nodes.push({ flag: f, np, ep, op });
    }

    // Orbit rings: walk the boundary of each barycentric point, alternating the two involutions
    // that FIX it. That visits node, edge, node, edge, ... which is what relax_orbs averages
    // (`for p in 0..ecs-1`: one getNc(p) and one getEc(p), fac = 2*ecs).
    for (const o of orbits) {
      const [a, b] = PAIR[o.ty];
      const rn = [], re = [];
      let f = o.members[0], t = a, guard = 4 * n + 4;
      do {
        rn.push(f); re.push(edgeIdx[t][f]);
        f = D.sigma[t][f]; t = (t === a ? b : a);
      } while (!(f === o.members[0] && t === a) && --guard > 0);
      o.ring = { nodes: rn, edges: re };
    }
    return { D, nodes, edges, orbits, fam, base, orbOf, edgeIdx };
  }

  // ---------------- Euclidean realization (Tegula's method, flat case) ----------------
  // Tegula: compute_radius -> compute_coords -> relax_coords. For curvature 0 compute_radius
  // degenerates -- it sets lr = hr = 0.5 and calls regula_falsi with identical endpoints, so
  // RAD = 0.5 with no root-finding. Corner orbits then sit at dist = rad / cos(beta/2) with
  // beta = pi - alph, i.e. dist = rad / sin(alph/2): the corner distance of the TANGENTIAL
  // polygon (every side tangent to a circle of radius rad). Euclidean closure is automatic,
  // since sum(pi - alph_j) = n*pi - (n-2)*pi = 2*pi for any n. That is why there is no root
  // find in the flat case -- and why Tegula cannot vary the domain shape.
  const RAD = 0.5;

  // The rotation order i = v * f * s (Orbit.java: "= v * f * s = 2 * PI / alph").
  //   v = m / r  -- the Delaney branching number
  //   f = fixpoint factor, 1 for a loop (interior orbit), 2 for a chain (orbit on a mirror)
  //   s = splits in the fundamental domain; 1 when the quotient is already a disk
  // An orbit lies on the mirror boundary iff one of the two involutions that FIX it has a fixed
  // point among its flags -- the same condition that makes a chamber side a boundary edge.
  function orbitOrders(D, I) {
    const mOf = [D.m12, null, D.m01];        // type 1 (edges) is m02 = 2 always
    const perType = [0, 0, 0];
    return I.orbits.map(o => {
      const [a, b] = PAIR[o.ty];
      const idx = perType[o.ty]++;
      const m = o.ty === 1 ? 2 : (mOf[o.ty][idx]);
      const r = rValue(D, a, b, o.members[0]);
      const v = m / r;
      const onMirror = o.members.some(f => D.sigma[a][f] === f || D.sigma[b][f] === f);
      const f = onMirror ? 2 : 1;
      const i = v * f;                       // s = 1 (disk case only)
      return { m, r, v, f, i, onMirror, alph: (2 * Math.PI) / i };
    });
  }

  // Boundary cycle of the quotient complex: the chamber sides with a single flag (sigma_ty(f) = f)
  // are mirrors and bound the disk. Returns the alternating cycle of orbit/edge indices.
  function boundaryCycle(I) {
    const bEdges = [];
    I.edges.forEach((e, i) => { if (e.nodes.length === 1) bEdges.push(i); });
    if (!bEdges.length) return null;
    const inc = new Map();                   // orbit -> boundary edges touching it
    for (const ei of bEdges) for (const oc of I.edges[ei].oc) {
      if (!inc.has(oc)) inc.set(oc, []);
      inc.get(oc).push(ei);
    }
    for (const [, es] of inc) if (es.length !== 2) return null;   // not a clean 1-manifold
    const start = bEdges[0];
    const cyc = [];                          // [{orbit, edge}] walking around
    let e = start, o = I.edges[start].oc[0], guard = 4 * bEdges.length + 4;
    do {
      cyc.push({ orbit: o, edge: e });
      const nx = I.edges[e].oc;
      o = (nx[0] === o) ? nx[1] : nx[0];     // other endpoint of this edge
      const es = inc.get(o);
      e = (es[0] === e) ? es[1] : es[0];     // other boundary edge at that orbit
    } while (e !== start && --guard > 0);
    return cyc.length === bEdges.length ? cyc : null;
  }

  // compute_coords, flat case. Places the border orbits, then the edge midpoints.
  function computeCoords(D, I) {
    const ord = orbitOrders(D, I);
    const cyc = boundaryCycle(I);
    if (!cyc) throw new Error('no clean mirror boundary (needs Glue-style cutting)');
    const P = I.orbits.map(() => null);

    // Corners are the orbits with i > 2; walk the border accumulating half-angles, exactly as
    // Tegula does (sum starts at pi/2).
    let sum = Math.PI / 2;
    const corners = [];
    for (const step of cyc) {
      const o = step.orbit, oi = ord[o];
      if (oi.i > 2) {
        const beta = Math.PI - oi.alph;
        sum += 0.5 * beta;
        const dist = RAD / Math.cos(0.5 * beta);
        P[o] = [dist * Math.cos(sum), dist * Math.sin(sum)];
        sum += 0.5 * beta;
        corners.push(o);
      }
    }
    if (!corners.length) throw new Error('no corner orbit (i > 2) on the border');

    // Non-corner border orbits are interpolated linearly between the corners bracketing them.
    const n = cyc.length;
    const startAt = cyc.findIndex(s => ord[s.orbit].i > 2);
    let run = [], prev = cyc[startAt].orbit;
    for (let k = 1; k <= n; k++) {
      const o = cyc[(startAt + k) % n].orbit;
      if (ord[o].i > 2) {
        for (let j = 0; j < run.length; j++) {
          const t = (j + 1) / (run.length + 1);
          P[run[j]] = [P[prev][0] + t * (P[o][0] - P[prev][0]),
                       P[prev][1] + t * (P[o][1] - P[prev][1])];
        }
        run = []; prev = o;
      } else run.push(o);
    }

    // Interior orbits (not on the border) start at the centroid of the placed border.
    let cx = 0, cy = 0, c = 0;
    for (const p of P) if (p) { cx += p[0]; cy += p[1]; c++; }
    cx /= c; cy /= c;
    for (let i = 0; i < P.length; i++) if (!P[i]) P[i] = [cx, cy];

    // Edge coordinates: flat geometry gives straight sides, so the midpoint of the two endpoints.
    const E = I.edges.map(e => [0.5 * (P[e.oc[0]][0] + P[e.oc[1]][0]),
                                0.5 * (P[e.oc[0]][1] + P[e.oc[1]][1])]);
    // Node (chamber) coordinates: the centroid of its 3 sides and 3 corners -- relax_nods' rule.
    const N = I.nodes.map(nd => {
      let x = 0, y = 0;
      for (let ty = 0; ty < 3; ty++) { x += E[nd.ep[ty]][0] + P[nd.op[ty]][0];
                                       y += E[nd.ep[ty]][1] + P[nd.op[ty]][1]; }
      return [x / 6, y / 6];
    });
    return { orbitPos: P, edgePos: E, nodePos: N, ord, cyc, corners };
  }

  // relax_coords: the three barycentric passes to convergence. Orbits with i > 1 are PINNED
  // (relax_orbs: `if (d.getOrb(op).getI() > 1) continue;`).
  function relaxCoords(I, C, opts) {
    const EPS = (opts && opts.eps) || 1e-10, MAXIT = (opts && opts.maxIter) || 20000;
    const { orbitPos: P, edgePos: E, nodePos: N, ord } = C;
    let it = 0, moved = true;
    while (moved && it++ < MAXIT) {
      moved = false;
      for (let i = 0; i < N.length; i++) {          // relax_nods: 3 edges + 3 orbits
        const nd = I.nodes[i]; let x = 0, y = 0;
        for (let ty = 0; ty < 3; ty++) { x += E[nd.ep[ty]][0] + P[nd.op[ty]][0];
                                         y += E[nd.ep[ty]][1] + P[nd.op[ty]][1]; }
        x /= 6; y /= 6;
        if (Math.abs(x - N[i][0]) >= EPS || Math.abs(y - N[i][1]) >= EPS) moved = true;
        N[i] = [x, y];
      }
      for (let i = 0; i < E.length; i++) {          // relax_edgs: 2 orbits + its chambers
        const e = I.edges[i];
        let x = P[e.oc[0]][0] + P[e.oc[1]][0], y = P[e.oc[0]][1] + P[e.oc[1]][1], f = 2;
        for (const fl of e.nodes) { x += N[fl - 1][0]; y += N[fl - 1][1]; f++; }
        x /= f; y /= f;
        if (Math.abs(x - E[i][0]) >= EPS || Math.abs(y - E[i][1]) >= EPS) moved = true;
        E[i] = [x, y];
      }
      for (let i = 0; i < P.length; i++) {          // relax_orbs: pinned when i > 1
        if (ord[i].i > 1) continue;
        const ring = I.orbits[i].ring; let x = 0, y = 0;
        for (let p = 0; p < ring.nodes.length; p++) {
          x += N[ring.nodes[p] - 1][0] + E[ring.edges[p]][0];
          y += N[ring.nodes[p] - 1][1] + E[ring.edges[p]][1];
        }
        const f = 2 * ring.nodes.length; x /= f; y /= f;
        if (Math.abs(x - P[i][0]) >= EPS || Math.abs(y - P[i][1]) >= EPS) moved = true;
        P[i] = [x, y];
      }
    }
    return { iterations: it, converged: !moved };
  }

  function realize(sym) {
    const D = parseSymbol(sym), I = incidence(D);
    const C = computeCoords(D, I);
    const rel = relaxCoords(I, C);
    return { D, I, C, rel };
  }

  const api = { parseSymbol, orbits2, chambers, rValue, branching, incidence, PAIR,
                RAD, orbitOrders, boundaryCycle, computeCoords, relaxCoords, realize };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.DsymGeom = api;
})(typeof window !== 'undefined' ? window : this);
